void main() {
  
  int firstValue = 19;
  int secondValue = 20;
  double thirdValue = 130.50;
  String firstWord = "tanga";
  
  
  print(firstValue);

  print(secondValue + firstValue);
  
  firstValue = 30;
  
  print(firstValue);
  print(thirdValue);
  print(firstWord);
  
  
//boolean for true and false 
  
  bool isAdult = false;
  
  print(isAdult);
  
  
// dynamic - it can take any value (int string bool etc.) THIS IS NOT RECOMMENDED
  
  dynamic isChild = 'boboooo';
  
  print(isChild);
  
  String someValue = '10';
  print(someValue.length);
  
  
  String greeting = "Hello, Kyle";
  
  print(greeting);
  
  greeting = '${greeting.length} Yoooo';
  
  
  // CURLY BRACKETS ARE USED FOR SPECIFIC PURPOSES LIKE LENGTH {greeting.length}
  print(greeting);
  
  //MULTIPLE LINE SAMPLE
  greeting = '''"Hello  
  World"
  ''';
  
  //PRINT WITH NEW LINE
  greeting = "Hello \nWorld";
  
  print(greeting);
}

  

